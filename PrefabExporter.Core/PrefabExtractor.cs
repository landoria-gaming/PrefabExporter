using System.Text;

namespace PrefabExporter.Core;

// Extracts selected prefab resources with a private AssetRipper process.
public static class PrefabExtractor
{
    // Extracts resources into a new prefab directory beside the application.
    public static async Task<string> Extract(string assetsPath, string refsPath, string name, string appDirectory,
        IProgress<string>? progress, CancellationToken cancellation, TextWriter? log = null, string? assetRipperPath = null)
    {
        ValidateName(name);
        var plan = Explorer.SelectForExtraction(assetsPath, refsPath, name, progress, cancellation);
        var selected = plan.Assets;
        int missing = plan.Missing;
        string root = Path.Combine(appDirectory, "output");
        string destination = Path.Combine(root, name);
        if (Directory.Exists(destination) || File.Exists(destination))
        {
            throw new IOException($"Output folder already exists: {destination}");
        }
        string executable = AssetRipperLocation.Resolve(assetRipperPath, appDirectory);
        using var session = new AssetRipperSession(executable);
        await session.WaitUntilReady(cancellation);
        string[] files = selected.Select(asset => asset.Source).Where(path => !string.IsNullOrEmpty(path))
            .Select(path => path!).Distinct(StringComparer.OrdinalIgnoreCase).ToArray();
        if (files.Length == 0 || files.Any(path => !File.Exists(path)))
        {
            throw new FileNotFoundException("One or more required game files are missing.");
        }
        progress?.Report($"Loading {files.Length} game files in AssetRipper...");
        await session.Load(files, cancellation);
        return await ExtractSelected(session, plan, name, root, destination, missing, progress, cancellation, log);
    }

    // Extracts into a temporary directory and publishes the completed output.
    private static async Task<string> ExtractSelected(AssetRipperSession session, ExtractionPlan plan, string name,
        string root, string destination, int missing, IProgress<string>? progress, CancellationToken cancellation,
        TextWriter? log)
    {
        Directory.CreateDirectory(root);
        string stage = Path.Combine(root, ".extract-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(stage);
        var result = new StringBuilder();
        var paths = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        int succeeded = 0;
        try
        {
            succeeded = await ExtractEach(session, plan.Assets, stage, result, paths, progress, cancellation, log);
            if (missing > 0)
            {
                string warning = $"WARNING: {missing} referenced objects could not be resolved.";
                result.AppendLine(warning);
                log?.WriteLine($"{DateTimeOffset.Now:O} {warning}");
            }
            if (succeeded == 0)
            {
                throw new InvalidOperationException("No assets could be extracted. " + result);
            }
            cancellation.ThrowIfCancellationRequested();
            await TryExportFbx(plan, paths, name, stage, result, progress, cancellation, log);
            cancellation.ThrowIfCancellationRequested();
            Directory.Move(stage, destination);
            return $"Extracted {succeeded} assets to: {destination}\n\n{result}" +
                "\nFBX export supports active static meshes with embedded color and normal textures. " +
                "Open the Blender file for unfiltered textures; FBX import may restore linear filtering. " +
                "Unity-specific shader effects may differ. Individual GLBs use a default material. " +
                "Shader text may be a placeholder generated by AssetRipper.";
        }
        finally
        {
            if (Directory.Exists(stage))
            {
                Directory.Delete(stage, true);
            }
        }
    }

    // Exports the assembled FBX and reports unsupported prefab features.
    private static async Task TryExportFbx(ExtractionPlan plan, Dictionary<string, string> paths, string name,
        string stage, StringBuilder result, IProgress<string>? progress, CancellationToken cancellation, TextWriter? log)
    {
        try
        {
            await BlenderFbxExporter.Export(plan, paths, name, stage, progress, cancellation);
            result.AppendLine(name + ".fbx");
            result.AppendLine(name + ".blend");
        }
        catch (Exception error) when (error is not OperationCanceledException)
        {
            File.Delete(Path.Combine(stage, name + ".fbx"));
            File.Delete(Path.Combine(stage, name + ".blend"));
            string warning = "WARNING: FBX export failed: " + error.Message;
            result.AppendLine(warning);
            log?.WriteLine($"{DateTimeOffset.Now:O} {warning}");
        }
    }

    // Extracts each selected asset and records any individual failures.
    private static async Task<int> ExtractEach(AssetRipperSession session, List<IndexedAsset> assets,
        string stage, StringBuilder result, Dictionary<string, string> paths, IProgress<string>? progress,
        CancellationToken cancellation, TextWriter? log)
    {
        var search = new AssetRipperSearch(session);
        int succeeded = 0;
        foreach (var asset in assets)
        {
            cancellation.ThrowIfCancellationRequested();
            progress?.Report($"Extracting {asset.Type}: {asset.Name ?? asset.AssetPath ?? "unnamed"}...");
            try
            {
                string filename = await ExtractAsset(session, search, asset, stage, cancellation);
                result.AppendLine(filename);
                paths[Explorer.Key(asset.Collection, asset.PathId)] = filename;
                succeeded++;
            }
            catch (Exception error) when (error is not OperationCanceledException)
            {
                string warning = $"WARNING: {asset.Type} {asset.Name ?? asset.AssetPath}: {error.Message}";
                result.AppendLine(warning);
                log?.WriteLine($"{DateTimeOffset.Now:O} {warning}");
            }
        }
        return succeeded;
    }

    // Extracts a single matching asset in a suitable format.
    private static async Task<string> ExtractAsset(AssetRipperSession session, AssetRipperSearch search,
        IndexedAsset asset, string stage, CancellationToken cancellation)
    {
        string view = await search.Find(asset, cancellation);
        string endpoint = asset.Type switch
        {
            "Texture2D" or "Sprite" => "/Assets/Image",
            "Mesh" => "/Assets/Model.glb",
            "Shader" => "/Assets/Text",
            "Material" or "GameObject" => "/Assets/Yaml",
            _ => throw new NotSupportedException("Unsupported asset type.")
        };
        string uri = view.Replace("/Assets/View", endpoint, StringComparison.Ordinal);
        if (asset.Type is "Texture2D" or "Sprite")
        {
            uri += "&Extension=png";
        }
        byte[] bytes = await session.GetBytes(uri, cancellation);
        if (asset.Type == "Sprite")
        {
            string metadata = await session.GetText(view.Replace("/Assets/View", "/Assets/Json", StringComparison.Ordinal), cancellation);
            bytes = SpriteCropper.Crop(bytes, metadata);
        }
        if (bytes.Length == 0)
        {
            throw new InvalidDataException("AssetRipper returned an empty file.");
        }
        ValidateContent(asset, bytes);
        string filename = OutputName(asset, stage);
        await File.WriteAllBytesAsync(Path.Combine(stage, filename), bytes, cancellation);
        return filename;
    }

    // Checks that AssetRipper returned a file in the expected format.
    private static void ValidateContent(IndexedAsset asset, byte[] bytes)
    {
        bool valid = asset.Type switch
        {
            "Mesh" => bytes.AsSpan().StartsWith("glTF"u8),
            "Texture2D" or "Sprite" => bytes.AsSpan().StartsWith(new byte[] { 137, 80, 78, 71, 13, 10, 26, 10 }),
            "Material" or "GameObject" => bytes.AsSpan().StartsWith("%YAML"u8),
            _ => bytes.Length > 0
        };
        if (!valid)
        {
            throw new InvalidDataException("AssetRipper returned an invalid or unsupported file.");
        }
    }

    // Creates a safe, unique relative output name for an asset.
    private static string OutputName(IndexedAsset asset, string stage)
    {
        string category = asset.Type switch
        {
            "Texture2D" => "textures", "Sprite" => "icons", "Mesh" => "meshes",
            "Material" => "materials", "Shader" => "shaders", _ => "prefab"
        };
        string extension = asset.Type switch
        {
            "Texture2D" or "Sprite" => ".png", "Mesh" => ".glb", "Shader" => ".shader.txt", _ => ".yaml"
        };
        string raw = !string.IsNullOrWhiteSpace(asset.Name) ? asset.Name :
            Path.GetFileNameWithoutExtension(asset.AssetPath ?? asset.Type ?? "asset");
        string name = string.Concat(raw.Select(c => Path.GetInvalidFileNameChars().Contains(c) ? '_' : c)).TrimEnd('.', ' ');
        if (string.IsNullOrWhiteSpace(name))
        {
            name = "asset";
        }
        string folder = Path.Combine(stage, "other", category);
        Directory.CreateDirectory(folder);
        string filename = name + extension;
        for (int i = 2; File.Exists(Path.Combine(folder, filename)); i++)
        {
            filename = $"{name}-{i}{extension}";
        }
        return Path.Combine("other", category, filename);
    }

    // Rejects names that could escape the output directory.
    private static void ValidateName(string name)
    {
        if (string.IsNullOrWhiteSpace(name) || name is "." or ".." || name.IndexOfAny(Path.GetInvalidFileNameChars()) >= 0 ||
            name.EndsWith('.') || name.EndsWith(' '))
        {
            throw new ArgumentException("Enter a valid exact prefab name.");
        }
    }
}
